// Inicializar el mapa (Pintar colores y asignar eventos)
document.addEventListener("DOMContentLoaded", () => {
    const municipiosSvg = document.querySelectorAll("#mapa-michoacan path");

    municipiosSvg.forEach(path => {
        const id = path.id;
        
        // Si el municipio existe en nuestro diccionario
        if(datosMunicipios[id]) {
            // Le asignamos su color (clase CSS)
            path.classList.add(datosMunicipios[id].region);

            // Le asignamos el evento click para mostrar la carta
            if(datosMunicipios[id].info) { // Solo asigna el evento si hay info para mostrar
                path.addEventListener("click", () => {
                    abrirCarta(id, datosMunicipios[id].info);
                });
            }
        }
    });
});

//Función para filtrar por región
function filtrarMapa(regionFiltro) {
    const municipiosSvg = document.querySelectorAll("#mapa-michoacan path");
    
    municipiosSvg.forEach(path => {
        const id = path.id;
        if(datosMunicipios[id]) {
            if (regionFiltro === 'todas') {
                path.classList.remove('opacado'); // Muestra todos
            } else {
                // Verifica si la región del municipio coincide con el filtro
                if (datosMunicipios[id].region === `region-${regionFiltro}`) {
                    path.classList.remove('opacado');
                } else {
                    path.classList.add('opacado'); // Apaga los demás
                }
            }
        }
    });
    cerrarCarta(); // Ocultar carta al cambiar de filtro
}

//Funciones para la Carta/Ventana
function abrirCarta(nombre, info) {
    const carta = document.getElementById("carta-info");
    const titulo = document.getElementById("municipio-nombre");
    const descripcion = document.getElementById("municipio-datos");

    titulo.textContent = nombre;
    descripcion.textContent = info;
    
    carta.classList.remove("oculto");
}

function cerrarCarta() {
    document.getElementById("carta-info").classList.add("oculto");
}
function nombreMunicipio(id){
    const municipio = datosMunicipios[id];
    return municipio ? municipio.municipio || id : id; // Devuelve el nombre del municipio o el ID si no se encuentra
}
document.addEventListener("DOMContentLoaded", () => {
    const municipiosSvg = document.querySelectorAll("#mapa-michoacan path");
    const tooltip = document.getElementById("tooltip-mapa"); // Seleccionamos el tooltip

    municipiosSvg.forEach(path => {
        const id = path.id;
        
        if(datosMunicipios[id]) {
            path.classList.add(datosMunicipios[id].region);

       
            path.addEventListener("mouseenter", () => {
                tooltip.textContent = datosMunicipios[id].municipio;
                tooltip.classList.remove("oculto"); // Se hacevisible
            });

            path.addEventListener("mousemove", (evento) => {
                tooltip.style.left = (evento.clientX + 15) + "px";
                tooltip.style.top = (evento.clientY + 15) + "px";
            });

            path.addEventListener("mouseleave", () => {
                tooltip.classList.add("oculto"); //Se oculta
            });
        }
    });
});